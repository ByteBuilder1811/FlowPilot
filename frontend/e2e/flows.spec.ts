test('H: side-effect ledger, determinism proof and breaking-version finder', async ({ page }) => {
  const c = await apiCtx()
  const ex = await loadExample('resilient')
  // v1 (brittle) fails -> case; v2 fixes; v3 reintroduces the bug
  const failed = await (await c.post(`/api/workflows/${ex.id}/run`, { data: { input: ex.sample_input } })).json()
  await expect.poll(async () => (await (await c.get(`/api/runs/${failed.run_id}`)).json()).status, { timeout: 15_000 }).toBe('failed')
  await c.post('/api/lab/cases', { data: { run_id: failed.run_id, name: 'flaky lookup' } })
  const setAttempts = async (n: number, note: string) => {
    const wf = await (await c.get(`/api/workflows/${ex.id}`)).json()
    wf.draft.nodes.find((x: any) => x.id === 'policy').data.config.max_attempts = n
    await c.put(`/api/workflows/${ex.id}`, { data: { definition: wf.draft } })
    await c.post(`/api/workflows/${ex.id}/versions`, { data: { note } })
  }
  await setAttempts(3, 'good'); await setAttempts(1, 'oops')
  await page.goto(`/runs/${failed.run_id}`)
  await expect(page.getByTestId('effects-ledger')).toContainText('No external side effects')
  await page.goto('/lab')
  await page.getByTestId('determinism-go').click()
  await expect(page.getByTestId('determinism-result')).toContainText('Deterministic', { timeout: 30_000 })
  await page.goto(`/compare?workflow=${ex.id}`)
  await page.getByTestId('matrix-go').click()
  await expect(page.getByTestId('culprit')).toContainText('broke in v3', { timeout: 40_000 })
  await expect(page.getByTestId('culprit')).toContainText('max_attempts')
})

